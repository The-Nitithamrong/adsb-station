def new_frame():
    img = Image.new("RGB", (W, H), PALETTE["bg"])
    d = ImageDraw.Draw(img)
    return img, d


def text(d, xy, s, font, color, anchor="la"):
    """วาด bitmap text. font: 'tiny'=3x5 · 'small'=5x7 · 'big'=5x7 x2 (10x14).
    anchor: [x: l/m/r][y: (top)/m]. s ถูกแปลงเป็น UPPERCASE."""
    if font == "tiny":
        glyphs, miss, gw, scale = _G3, _MISSING3, 3, 1
    else:
        glyphs, miss, gw, scale = _G, _MISSING, 5, (2 if font == "big" else 1)
    gh = len(miss) * scale           # จำนวนแถวของ glyph (5 หรือ 7) x scale
    adv = gw * scale + scale         # กว้างตัวอักษร + ช่องไฟ 1 (คูณ scale)
    s = str(s).upper()
    w = len(s) * adv
    x, y = xy
    if   anchor[0] == "r": x -= w
    elif anchor[0] == "m": x -= w // 2
    if len(anchor) > 1 and anchor[1] == "m": y -= gh // 2

    for ch in s:
        g = glyphs.get(ch, miss)
        for ry, row in enumerate(g):
            for rx, bit in enumerate(row):
                if bit == "1":
                    x0, y0 = x + rx * scale, y + ry * scale
                    if scale == 1:
                        d.point((x0, y0), fill=color)
                    else:
                        d.rectangle([x0, y0, x0 + scale - 1, y0 + scale - 1], fill=color)
        x += adv


def draw_header(d, now):
    """เวลา (big) + วันที่ (small) + เส้นคั่น"""
    text(d, (32, 1),  now.strftime("%H:%M"),    "big",   PALETTE["time"], anchor="ma")   # y1..14
    text(d, (32, 16), now.strftime("%a %d %b"), "small", PALETTE["date"], anchor="ma")   # y16..22
    d.line([(3, 25), (60, 25)], fill=PALETTE["divider"])


def draw_status_frame(d, health):
    """กรอบรอบโซนหมุนหน้า สีตามสุขภาพ = health at-a-glance"""
    c = HEALTH.get(health, HEALTH["stale"])
    dim = tuple(v // 3 for v in c)
    d.rectangle([(1, 27), (62, 62)], outline=dim)


def draw_plane(d, x, y, color):
    """เครื่องบินพิกเซล 7x7 วาดเอง"""
    for dx, dy in [(3,0),(3,1),(0,3),(1,3),(2,3),(3,3),(4,3),(5,3),(6,3),
                   (3,4),(3,5),(2,6),(4,6)]:
        d.point((x + dx, y + dy), fill=color)
